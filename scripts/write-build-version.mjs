import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const target = resolve("src/generated/build-info.ts");
const version = new Date().toISOString();

await mkdir(dirname(target), { recursive: true });
await writeFile(
  target,
  `// Generated by npm run prebuild. Keep the fallback committed for dev and tests.\nexport const BUILD_VERSION = ${JSON.stringify(version)};\n`,
  "utf8"
);

console.log(`BUILD_VERSION=${version}`);
